#!/usr/bin/env python3
"""Generate cpp/core/keywords_data.inc from Notepad++'s langs.model.xml.

Notepad++ keeps the canonical default keyword tables for every language it
ships in PowerEditor/src/langs.model.xml.  pwa-code reuses exactly those words
so highlighting matches Notepad++ instead of inventing a new list.

This is a build-time script.  The generated .inc is committed, so building the
app never needs a Notepad++ checkout.

Usage:
    python3 build/gen_keywords.py [path/to/langs.model.xml]

Default source:
    /home/cqwrteur/libraries/notepad-plus-plus/PowerEditor/src/langs.model.xml
"""
from __future__ import annotations

import os
import sys
import xml.etree.ElementTree as ET

DEFAULT_XML = "/home/cqwrteur/libraries/notepad-plus-plus/PowerEditor/src/langs.model.xml"

# (notepad++ language name, C++ identifier, extra keywords)
# C++ deliberately gains throws and return_failure (herbceptions / fast_io).
LANGUAGES = [
    ("c", "c", []),
    ("cpp", "cpp", ["throws", "return_failure"]),
    ("objc", "objc", []),
    ("python", "python", []),
    ("javascript", "javascript", []),
    ("javascript.js", "javascript_js", []),
    ("typescript", "typescript", []),
    ("java", "java", []),
    ("cs", "csharp", []),
    ("rust", "rust", []),
    ("go", "go", []),
    ("swift", "swift", []),
    ("ruby", "ruby", []),
    ("php", "php", []),
    ("perl", "perl", []),
    ("bash", "bash", []),
    ("batch", "batch", []),
    ("powershell", "powershell", []),
    ("sql", "sql", []),
    ("html", "html", []),
    ("xml", "xml", []),
    ("css", "css", []),
    ("json", "json", []),
    ("json5", "json5", []),
    ("yaml", "yaml", []),
    ("toml", "toml", []),
    ("ini", "ini", []),
    ("makefile", "makefile", []),
    ("cmake", "cmake", []),
    ("diff", "diff", []),
    ("lisp", "lisp", []),
    ("scheme", "scheme", []),
    ("haskell", "haskell", []),
    ("lua", "lua", []),
    ("d", "d", []),
    ("asm", "asm", []),
    ("verilog", "verilog", []),
    ("vhdl", "vhdl", []),
    ("latex", "latex", []),
    ("tex", "tex", []),
    ("r", "r", []),
    ("raku", "raku", []),
]

# word-list name -> token class.  1 = keyword, 2 = type/identifier-ish.
LIST_KIND = {
    "instre1": 1,
    "instre2": 1,
    "type1": 2,
    "type2": 2,
    "type3": 2,
    "type4": 2,
    "type5": 2,
    "type6": 2,
    "substyle1": 1,
    "substyle2": 1,
    "substyle3": 1,
    "substyle4": 1,
    "substyle5": 1,
}


def cppify_comment(text: str | None) -> str:
    if not text:
        return "{}"
    return 'u8"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    xml_path = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("NPP_LANGS_XML", DEFAULT_XML)
    root = ET.parse(xml_path).getroot()
    by_name = {lang.get("name"): lang for lang in root.iter("Language")}

    out: list[str] = []
    out.append("// Generated by build/gen_keywords.py from Notepad++ langs.model.xml.")
    out.append("// Do not edit by hand.  Re-run the generator instead.")
    out.append("#pragma once")
    out.append("")
    out.append("namespace pwa::keywords")
    out.append("{")
    out.append("")
    out.append("struct word_entry")
    out.append("{")
    out.append("\t::fast_io::u8string_view word{};")
    out.append("\t::std::uint_least8_t kind{}; // 1 keyword, 2 type")
    out.append("};")
    out.append("")
    out.append("struct language")
    out.append("{")
    out.append("\t::fast_io::u8string_view name{};")
    out.append("\t::fast_io::u8string_view exts{}; // space separated")
    out.append("\t::fast_io::u8string_view line_comment{};")
    out.append("\t::fast_io::u8string_view block_open{};")
    out.append("\t::fast_io::u8string_view block_close{};")
    out.append("\tword_entry const *words{};")
    out.append("\t::std::size_t word_count{};")
    out.append("};")
    out.append("")

    docs: list[tuple[str, list[tuple[str, int]], str, str, str, str]] = []
    for npp_name, ident, extra in LANGUAGES:
        lang = by_name.get(npp_name)
        if lang is None:
            print(f"warning: {npp_name} missing from {xml_path}", file=sys.stderr)
            continue
        words: dict[str, int] = {}
        for kw in lang.findall("Keywords"):
            name = kw.get("name", "")
            kind = LIST_KIND.get(name)
            if kind is None:
                continue
            text = (kw.text or "").strip()
            if not text or len(text) > 24000:  # skip pathological user lists
                continue
            for word in text.split():
                if not word or len(word) > 128:
                    continue
                # Notepad++ separates some lists by spaces already.
                words.setdefault(word, kind)
        for word in extra:
            words[word] = 1
        if not words:
            continue
        ordered = sorted(words.items(), key=lambda kv: kv[0].encode("utf-8"))
        docs.append(
            (
                ident,
                ordered,
                lang.get("ext") or "",
                lang.get("commentLine") or "",
                lang.get("commentStart") or "",
                lang.get("commentEnd") or "",
            )
        )

    for ident, words, exts, line_comment, block_open, block_close in docs:
        out.append(f"inline constexpr word_entry {ident}_words[]{{")
        for word, kind in words:
            esc = word.replace("\\", "\\\\").replace('"', '\\"')
            out.append(f'\t{{u8"{esc}", {kind}}},')
        out.append("};")
        out.append("")

    out.append("inline constexpr language languages[]{")
    for ident, words, exts, line_comment, block_open, block_close in docs:
        exts_esc = exts.replace("\\", "\\\\").replace('"', '\\"')
        out.append(
            f'\t{{u8"{ident}", u8"{exts_esc}", {cppify_comment(line_comment)}, '
            f"{cppify_comment(block_open)}, {cppify_comment(block_close)}, "
            f"{ident}_words, sizeof({ident}_words) / sizeof({ident}_words[0])}},"
        )
    out.append("};")
    out.append("")
    out.append("inline constexpr ::std::size_t language_count{sizeof(languages) / sizeof(languages[0])};")
    out.append("")
    out.append("} // namespace pwa::keywords")
    out.append("")

    dest = os.path.join(os.path.dirname(__file__), "..", "cpp", "core", "keywords_data.inc")
    with open(os.path.abspath(dest), "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print(f"wrote {os.path.abspath(dest)} ({len(docs)} languages)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
